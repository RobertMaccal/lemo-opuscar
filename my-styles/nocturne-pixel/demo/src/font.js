const TRACK = 2;
export const GLYPHS = G;
export function textWidth(s, sc = 1) { let w = 0; for (const ch of s) w += (G[ch] || G[' '])[0].length + TRACK; return (w - TRACK) * sc; }
// p: 0..1 dissolve; returns the box in native pixels
export function drawText(buf, s, cx, y, sc, p, col = C.w9, sh = C.n0) {
  const w = textWidth(s, sc), x0 = Math.round(cx - w / 2); let x = x0;
  for (const ch of s) { const g = G[ch] || G[' '];
    for (let j = 0; j < 7; j++) for (let i = 0; i < g[j].length; i++) if (g[j][i] === '1')
      for (let a = 0; a < sc; a++) for (let b = 0; b < sc; b++) { const px = x + i * sc + a, py = y + j * sc + b;
        if (bayer(px, py) < p) { buf.px(px + 1, py + 1, sh); } }
    x += (g[0].length + TRACK) * sc; }
  x = x0;
  for (const ch of s) { const g = G[ch] || G[' '];
    for (let j = 0; j < 7; j++) for (let i = 0; i < g[j].length; i++) if (g[j][i] === '1')
      for (let a = 0; a < sc; a++) for (let b = 0; b < sc; b++) { const px = x + i * sc + a, py = y + j * sc + b; if (bayer(px, py) < p) buf.px(px, py, col); }
    x += (g[0].length + TRACK) * sc; }
  return { x0, y0: y, x1: x0 + w + 1, y1: y + 7 * sc + 1 };
}
